# Original local NES pattern for emulator QA. No third-party game content.
from pathlib import Path
code=[];labels={};fix=[]
def emit(*b):code.extend(b)
def label(n):labels[n]=0x8000+len(code)
def branch(op,n):emit(op,0);fix.append((len(code)-1,n,'rel'))
def jmp(n):emit(0x4c,0,0);fix.append((len(code)-2,n,'abs'))
emit(0x78,0xd8,0xa2,0xff,0x9a,0xe8,0x8e,0x00,0x20,0x8e,0x01,0x20)
label('wait');emit(0x2c,0x02,0x20);branch(0x10,'wait')
emit(0xa9,0x3f,0x8d,0x06,0x20,0xa9,0x00,0x8d,0x06,0x20,0xa2,0)
label('palette');emit(0xa9,0x21,0x8d,0x07,0x20,0xa9,0x30,0x8d,0x07,0x20,0xa9,0x11,0x8d,0x07,0x20,0xa9,0x0f,0x8d,0x07,0x20,0xe8,0xe0,8);branch(0xd0,'palette')
emit(0xa9,0x20,0x8d,0x06,0x20,0xa9,0,0x8d,0x06,0x20,0xa0,4,0xa2,0)
label('fill');emit(0xa9,1,0x8d,0x07,0x20,0xe8);branch(0xd0,'fill');emit(0x88);branch(0xd0,'fill')
emit(0xa9,0,0x8d,0x05,0x20,0x8d,0x05,0x20,0xa9,0x0a,0x8d,0x01,0x20)
label('loop');jmp('loop')
for at,n,kind in fix:
 addr=labels[n]
 if kind=='rel':code[at]=(addr-(0x8000+at+1))&255
 else:code[at]=addr&255;code[at+1]=addr>>8
prg=bytearray(16384);prg[:len(code)]=bytes(code)
for at in [0x3ffa,0x3ffc,0x3ffe]:prg[at:at+2]=bytes([0,0x80])
chr=bytearray(8192);chr[16:24]=bytes([0x7c,0x42,0x42,0x7c,0x40,0x40,0x40,0])
p=Path('tools/fixtures');p.mkdir(exist_ok=True);(p/'pacific-test.nes').write_bytes(b'NES\x1a'+bytes([1,1])+bytes(10)+prg+chr)
